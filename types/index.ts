// Ledger entry kinds. Transfer is its own type (never an expense category) - see V2_SPEC Part B.
export type TransactionType = 'income' | 'expense' | 'transfer';
// Categories only classify income/expense; 'savings' is kept for existing category rows.
export type CategoryType = 'income' | 'expense' | 'savings';
// Where income lands / expenses are paid from. Goals can never be an expense source.
export type Account = 'available' | 'saved';
// A transfer endpoint additionally allows a specific goal (see fromGoalId / toGoalId).
export type TransferEndpoint = Account | 'goal';
// A user-managed list of ISO-ish currency codes (see Settings → Currencies), not a fixed union.
export type CurrencyCode = string;

export interface Currency {
  code: string;
  name: string;
  isDefault: boolean;
}

export interface Category {
  id: string;
  name: string;
  type: CategoryType;
  icon: string;
  color: string;
  isDefault: boolean;
}

// Every row is an immutable ledger entry. Balances are derived from these rows (utils/balances.ts),
// never stored. `amount`/`currency` are display-only; only `amountETB` ever enters a sum.
export interface Transaction {
  id: string;
  type: TransactionType;
  amount: number;
  currency: CurrencyCode;
  amountETB: number;
  exchangeRate: number;
  category: string;
  source: string;
  // Income destination / expense pay-from. Null for transfers.
  account: Account | null;
  // Transfer endpoints. Null for income/expense.
  fromAccount: TransferEndpoint | null;
  fromGoalId: string | null;
  toAccount: TransferEndpoint | null;
  toGoalId: string | null;
  date: string;
  timestamp: string;
  note: string | null;
  // True for rows generated by a recurring rule. Only manually recorded activity counts for the streak.
  isAutomatic: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface TransactionInput {
  type: TransactionType;
  amount: number;
  currency: CurrencyCode;
  // Per-transaction override of the stored rate (X -> ETB). Never written back to the rate table.
  rateOverride?: number | null;
  category?: string;
  source?: string;
  account?: Account | null;
  fromAccount?: TransferEndpoint | null;
  fromGoalId?: string | null;
  toAccount?: TransferEndpoint | null;
  toGoalId?: string | null;
  date: string;
  note?: string | null;
  isAutomatic?: boolean;
}

export interface ExchangeRate {
  id: string;
  fromCurrency: CurrencyCode;
  toCurrency: CurrencyCode;
  rate: number;
  updatedAt: string;
}

export type GoalStatus = 'active' | 'completed' | 'abandoned';

export interface Goal {
  id: string;
  name: string;
  // Always ETB (V2 Part D).
  targetAmount: number;
  deadline: string | null;
  status: GoalStatus;
  createdAt: string;
  updatedAt: string;
}

export interface GoalInput {
  name: string;
  targetAmount: number;
  deadline?: string | null;
}

export interface Budget {
  id: string;
  category: string;
  monthlyLimit: number;
  currency: CurrencyCode;
  createdAt: string;
  updatedAt: string;
}

export interface BudgetInput {
  category: string;
  monthlyLimit: number;
  currency: CurrencyCode;
}

export type RecurringFrequency = 'daily' | 'weekly' | 'monthly';
export type RecurringType = 'income' | 'expense';

export interface RecurringTransaction {
  id: string;
  type: RecurringType;
  account: Account;
  amount: number;
  currency: CurrencyCode;
  category: string;
  source: string;
  note: string | null;
  frequency: RecurringFrequency;
  startDate: string;
  lastGeneratedDate: string | null;
  isActive: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface RecurringTransactionInput {
  type: RecurringType;
  account: Account;
  amount: number;
  currency: CurrencyCode;
  category: string;
  source: string;
  note?: string | null;
  frequency: RecurringFrequency;
  startDate: string;
}

// An occurrence the recurring generator could not post (e.g. it would overdraw Available).
export interface RecurringFailure {
  ruleId: string;
  category: string;
  date: string;
  reason: string;
}

export type MilestoneType = 'goal_completed' | 'streak' | 'income_growth' | 'manual';

export interface Milestone {
  id: string;
  title: string;
  description: string;
  date: string;
  type: MilestoneType;
  createdAt: string;
}

export interface UserOrigin {
  id: string;
  storyText: string;
  startingPoint: string;
  whyBuilding: string;
  updatedAt: string;
}

export interface UserOriginInput {
  storyText: string;
  startingPoint: string;
  whyBuilding: string;
}

// All snapshot amounts are ETB. `savings` is the month's net change in Saved + Goals.
export interface MonthlySnapshot {
  id: string;
  month: string;
  income: number;
  expenses: number;
  savings: number;
  currency: CurrencyCode;
  createdAt: string;
}

export interface FinanceStoreState {
  transactions: Transaction[];
  categories: Category[];
  exchangeRates: ExchangeRate[];
  goals: Goal[];
  budgets: Budget[];
  recurringTransactions: RecurringTransaction[];
  milestones: Milestone[];
  origin: UserOrigin | null;
  monthlySnapshots: MonthlySnapshot[];
  currencies: Currency[];
  homeCurrency: CurrencyCode;
  isReady: boolean;
  loadData: () => Promise<void>;
  addTransaction: (input: TransactionInput) => Promise<Transaction>;
  updateTransaction: (id: string, input: TransactionInput) => Promise<Transaction>;
  deleteTransaction: (id: string) => Promise<void>;
  addCategory: (input: Omit<Category, 'id' | 'isDefault'>) => Promise<Category>;
  updateCategory: (id: string, input: Omit<Category, 'id' | 'isDefault'>) => Promise<void>;
  deleteCategory: (id: string) => Promise<void>;
  setHomeCurrency: (currency: CurrencyCode) => void;
  upsertExchangeRate: (fromCurrency: CurrencyCode, toCurrency: CurrencyCode, rate: number) => Promise<ExchangeRate>;
  addCurrency: (code: string, name: string) => Promise<Currency>;
  deleteCurrency: (code: string) => Promise<void>;
  addGoal: (input: GoalInput) => Promise<Goal>;
  updateGoal: (id: string, input: GoalInput) => Promise<void>;
  deleteGoal: (id: string) => Promise<void>;
  setGoalStatus: (id: string, status: GoalStatus) => Promise<void>;
  contributeToGoal: (goalId: string, amount: number, from: Account) => Promise<Transaction>;
  upsertBudget: (input: BudgetInput) => Promise<Budget>;
  deleteBudget: (id: string) => Promise<void>;
  addRecurringTransaction: (input: RecurringTransactionInput) => Promise<RecurringTransaction>;
  toggleRecurringTransaction: (id: string, isActive: boolean) => Promise<void>;
  deleteRecurringTransaction: (id: string) => Promise<void>;
  saveOrigin: (input: UserOriginInput) => Promise<UserOrigin>;
  addMilestone: (input: Omit<Milestone, 'id' | 'createdAt'>) => Promise<Milestone>;
}
