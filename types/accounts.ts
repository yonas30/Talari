import { ExchangeRate, GoalStatus } from './index';

// Phase 5 accounts model (V2_SPEC Parts B, C, F). These types are separate from types/index.ts on purpose: the running app
// still uses the old Available/Saved model until Phase 5B switches the store and screens over.

export type AccountType = 'cash' | 'wallet' | 'bank';

export interface MoneyAccount {
  id: string;
  name: string;
  type: AccountType;
  // 'ETB', or a foreign code that has a stored rate. Fixed once the account has any entry.
  currency: string;
  // Set from the type when the account is created (constants/accounts.ts).
  colour: string;
  sortOrder: number;
  archived: boolean;
  // Stored only. No SMS behaviour exists yet (V2_SPEC Part A).
  smsSender: string | null;
  lastDigits: string | null;
  createdAt: string;
}

// Where an imported entry's date came from (V2_SPEC Part Z): printed in the message, taken from the other side of a transfer, decoded from
// a CBE receipt reference, the batch date chosen on the paste screen, or set by the owner. Only 'batch' is an estimate.
export type DateSource = 'message' | 'paired' | 'receipt' | 'batch' | 'manual';
export const DATE_SOURCES: readonly DateSource[] = ['message', 'paired', 'receipt', 'batch', 'manual'];

// income / expense / transfer are what the owner records. opening / adjustment are system kinds: they count in an account's
// balance but never in income, expenses, categories or Insights, and never for the streak.
export type EntryType = 'income' | 'expense' | 'transfer' | 'opening' | 'adjustment';

// One immutable ledger row.
//  - income / expense / opening / adjustment: `accountId` is the account; from/to are null.
//  - transfer: `accountId` is null; `fromAccountId` / `toAccountId` are set. `amount` is the from-leg in the from-account's
//    currency, `toAmount` the to-leg in the to-account's currency; `amountETB` / `toAmountETB` are the ETB value of each leg.
//  - a transfer fee is its own expense row with `linkedTransferId` set.
export interface AccountEntry {
  id: string;
  type: EntryType;
  accountId: string | null;
  amount: number;
  currency: string;
  amountETB: number;
  exchangeRate: number;
  category: string;
  source: string;
  fromAccountId: string | null;
  toAccountId: string | null;
  toAmount: number | null;
  toAmountETB: number | null;
  linkedTransferId: string | null;
  date: string;
  timestamp: string;
  note: string | null;
  // True for rows generated by a recurring rule. They never count for the streak.
  isAutomatic: boolean;
  // Only on entries imported from an SMS; absent on every other entry and once the owner has confirmed or edited the date. A label only: it
  // never affects a balance.
  dateSource?: DateSource;
  createdAt: string;
  updatedAt: string;
}

// 'manual' = the owner added to / withdrew from a goal. 'auto_reduce' = reserved money was spent and the goal shrank.
export type AllocationKind = 'manual' | 'auto_reduce';

// Append-only. Positive reserves money for a goal inside an account, negative frees it. A goal's amount is the sum of its rows.
export interface GoalAllocation {
  id: string;
  goalId: string;
  accountId: string;
  amount: number;
  date: string;
  kind: AllocationKind;
  createdAt: string;
}

export interface AccountGoal {
  id: string;
  name: string;
  targetAmount: number;
  deadline: string | null;
  status: GoalStatus;
  // An ETB account. Only changeable while the goal's amount is zero.
  heldInAccountId: string;
  createdAt: string;
  updatedAt: string;
}

// Stored (unlike budget alerts, which are recomputed): this event cannot be derived from the data afterwards.
export interface ReserveNotification {
  id: string;
  kind: 'goal_reserve_used';
  goalId: string;
  accountId: string;
  // How much reserved money was used, and what the goal held afterwards (both ETB).
  amount: number;
  amountAfter: number;
  createdAt: string;
  read: boolean;
}

// Everything the pure ledger functions read. Rates and the currency list live elsewhere in the app; they are passed in.
export interface AccountsState {
  accounts: MoneyAccount[];
  entries: AccountEntry[];
  goals: AccountGoal[];
  allocations: GoalAllocation[];
  notifications: ReserveNotification[];
  rates: ExchangeRate[];
  // Codes on the Currencies & Exchange Rates screen.
  currencies: string[];
}
